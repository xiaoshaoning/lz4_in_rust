//! A Rust port of [LZ4](https://github.com/lz4/lz4), byte-compatible with the C reference
//! implementation (v1.11.1).
//!
//! `#![forbid(unsafe_code)]`: the port is **absolutely safe** — no `unsafe`, no raw pointers.
//! Where the C code leans on pointer arithmetic past the end of a buffer, this port keeps
//! explicit index invariants instead (see `docs/DESIGN.md` §2), so the compiler elides the bounds
//! checks and the behaviour stays defined for every input, including corrupt ones.
//!
//! Layers, in implementation order:
//!
//! | module       | format                | reference C code | state |
//! |--------------|-----------------------|------------------|-------|
//! | [`block`]    | LZ4 block             | `lib/lz4.c`      | done  |
//! | [`level`]    | `-1..-12` → parser    | `lib/lz4frame.c` | done  |
//! | [`par`]      | independent blocks    | — (new)          | done  |
//! | [`hc`]       | LZ4 block, high ratio | `lib/lz4hc.c`    | done  |
//! | [`frame`]    | LZ4 frame, streaming  | `lib/lz4frame.c` | done  |
//!
//! Compatibility is the contract: `lz4 -d` must read what we produce, and every block
//! `lz4` produces must decode here. `tests/` checks both directions against fixtures
//! generated by the C library itself (`tools/build_oracle.sh`).
//!
//! # Example
//!
//! ```
//! // the block API: fastest, no framing
//! let data = b"the quick brown fox jumps over the lazy dog, again and again".repeat(4);
//! let mut packed = vec![0u8; lz4_in_rust::block::compress_bound(data.len())];
//! let size = lz4_in_rust::block::compress_into(&data, &mut packed, 1).unwrap();
//! let mut back = vec![0u8; data.len()];
//! let decoded = lz4_in_rust::block::decompress_into(&packed[..size], &mut back).unwrap();
//! assert_eq!(decoded, data.len());
//! assert_eq!(back, data);
//!
//! // the frame format: a `.lz4` file, byte-identical to the reference tool
//! let frame = lz4_in_rust::frame::compress(&data, &lz4_in_rust::frame::Opts::default()).unwrap();
//! let decoded = lz4_in_rust::frame::decompress(&frame).unwrap();
//! assert_eq!(decoded.content, data);
//! ```

#![forbid(unsafe_code)]
#![deny(missing_docs)]

pub mod block;
pub mod frame;
pub mod hc;
pub mod level;
pub mod par;
pub mod xxhash;

/// Every way this crate can fail.
///
/// One enum for all layers, so callers need a single `?` and no per-layer error types.
/// Decompression errors are expected on untrusted input: no input may cause a panic.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    /// Input ended in the middle of a token, a length, an offset, or a literal run.
    Truncated,
    /// A match offset of 0, or a match that points before the start of the block
    /// (the caller must supply the dictionary as a prefix of `dst`).
    InvalidOffset(usize),
    /// The destination slice cannot hold the decoded result.
    OutputTooSmall {
        /// Bytes the result needs.
        need: usize,
        /// Bytes the destination has.
        have: usize,
    },
    /// A block decoded to a different size than its slot: either the stream is corrupt or
    /// the caller's block layout (block size / total length) does not match the data.
    BlockSizeMismatch {
        /// Bytes the block's slot holds.
        expected: usize,
        /// Bytes the block decoded to.
        got: usize,
    },
    /// The number of blocks handed to the parallel decoder does not match the layout.
    BlockCountMismatch {
        /// Blocks the layout implies.
        expected: usize,
        /// Blocks the caller supplied.
        got: usize,
    },
    /// A single input block exceeds the format limit (`LZ4_MAX_INPUT_SIZE`).
    InputTooLarge(usize),
    /// `xxh32` digest in the data does not match the data.
    ChecksumMismatch {
        /// Digest stored in the data.
        expected: u32,
        /// Digest computed from it.
        actual: u32,
    },
    /// The frame header or block structure is malformed; the reason names the field.
    InvalidFrame(&'static str),
    /// Syntactically valid data using a feature this port does not implement.
    Unsupported(&'static str),
}

impl core::fmt::Display for Error {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Error::Truncated => f.write_str("compressed input is truncated"),
            Error::InvalidOffset(o) => write!(f, "invalid match offset {o}"),
            Error::OutputTooSmall { need, have } => {
                write!(f, "output too small: need {need} bytes, have {have}")
            }
            Error::BlockSizeMismatch { expected, got } => {
                write!(f, "block decoded to {got} bytes, slot holds {expected}")
            }
            Error::BlockCountMismatch { expected, got } => {
                write!(f, "expected {expected} blocks, got {got}")
            }
            Error::InputTooLarge(n) => write!(f, "input block of {n} bytes is too large"),
            Error::ChecksumMismatch { expected, actual } => {
                write!(
                    f,
                    "checksum mismatch: expected {expected:08x}, got {actual:08x}"
                )
            }
            Error::InvalidFrame(what) => write!(f, "invalid frame: {what}"),
            Error::Unsupported(what) => write!(f, "unsupported feature: {what}"),
        }
    }
}

impl std::error::Error for Error {}
